export function translateUiText(text: string, lang: Lang | string = "fa") {
  const normalized = canonicalizeUiText(text);
  if (!normalized) return text;
  if (lang !== "fa" && lang !== "ar") return text;
  return faExactCopy[normalized] ?? faCopy[normalized] ?? translateFaPattern(normalized) ?? translateGeneratedLabel(normalized) ?? text;
}

export function translateErrorText(text: string) {
  const normalized = canonicalizeUiText(text);
  if (!normalized) return "انجام درخواست با خطا روبه‌رو شد. لطفاً دوباره تلاش کنید.";
  if (/[\u0600-\u06ff]/.test(normalized)) return normalized;
  return faExactCopy[normalized] ?? faCopy[normalized] ?? "انجام درخواست با خطا روبه‌رو شد. لطفاً دوباره تلاش کنید.";
}

export function canonicalizeUiText(text: string) {
  return text.trim().replace(/\s+/g, " ");
}

function translateGeneratedLabel(text: string) {
  if (/[\u0600-\u06FF]/.test(text)) return text;
  const normalized = text.replace(/[_.-]+/g, " ").replace(/\s+/g, " ").trim();
  const exact = faExactCopy[normalized]
    ?? faCopy[normalized]
    ?? faExactCopy[normalized.toUpperCase()]
    ?? faCopy[normalized.toUpperCase()]
    ?? faExactCopy[normalized.toLowerCase()]
    ?? faCopy[normalized.toLowerCase()]
    ?? normalizedExactCopy.get(normalized.toLocaleLowerCase("en-US"));
  if (exact) return exact;

  // Word-by-word translation produces mixed labels and keeps English word
  // order (for example, "Referral Links" became "معرفی Links"). Only a
  // single generated token is safe here; complete phrases belong in the exact
  // copy catalog where Persian grammar can be reviewed.
  if (/\s/.test(normalized)) return undefined;
  return faWords[normalized.toLocaleLowerCase("en-US")];
}

function translateFaPattern(text: string) {
  let match = text.match(/^You can attach up to (\d+) files\.$/);
  if (match) return `حداکثر می‌توانید ${match[1]} فایل پیوست کنید.`;

  match = text.match(/^(.+): Maximum file size is (.+)\.$/);
  if (match) return `حداکثر حجم مجاز برای فایل «${match[1]}» برابر ${match[2]} است.`;

  match = text.match(/^Maximum file size: (.+) · (\d+) files maximum$/);
  if (match) return `حداکثر حجم هر فایل: ${match[1]} · حداکثر ${match[2]} فایل`;

  match = text.match(/^Purchased (.+) for (.+) ([A-Z_]+)$/);
  if (match) return `در تاریخ ${match[1]} به مبلغ ${match[2]} ${translateGeneratedLabel(match[3]) ?? match[3]} خریداری شد`;

  match = text.match(/^Changed from (.+) to (.+)$/);
  if (match) {
    const from = translateGeneratedLabel(match[1]) ?? match[1];
    const to = translateGeneratedLabel(match[2]) ?? match[2];
    return `از «${from}» به «${to}» تغییر کرد`;
  }

  match = text.match(/^Translated from (.+) to (.+) via (.+)$/);
  if (match) return `از ${match[1]} به ${match[2]} با ${match[3]} ترجمه شد`;

  return undefined;
}
